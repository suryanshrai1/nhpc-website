-- ============================================================
-- Table: navigation_menu
-- Description : Website Navigation Menu
-- ============================================================

CREATE TABLE navigation_menu (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    parent_id BIGINT,

    label VARCHAR(100) NOT NULL,

    route VARCHAR(255) NOT NULL,

    icon VARCHAR(100),

    menu_location VARCHAR(30) NOT NULL DEFAULT 'HEADER',

    display_order INTEGER NOT NULL DEFAULT 1,

    is_visible BOOLEAN NOT NULL DEFAULT TRUE,

    open_in_new_tab BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_navigation_menu PRIMARY KEY (id),

    CONSTRAINT fk_navigation_menu_parent
        FOREIGN KEY (parent_id)
        REFERENCES navigation_menu(id)
        ON DELETE SET NULL,

    CONSTRAINT uq_navigation_menu_route
        UNIQUE (route),

    CONSTRAINT chk_navigation_menu_display_order
        CHECK (display_order > 0),

    CONSTRAINT chk_navigation_menu_location
        CHECK (menu_location IN ('HEADER', 'FOOTER'))

);

CREATE INDEX idx_navigation_menu_parent
ON navigation_menu(parent_id);

CREATE INDEX idx_navigation_menu_order
ON navigation_menu(display_order);

CREATE INDEX idx_navigation_menu_visible
ON navigation_menu(is_visible);

CREATE INDEX idx_navigation_menu_location
ON navigation_menu(menu_location);

CREATE TRIGGER trg_navigation_menu_updated_at
BEFORE UPDATE ON navigation_menu
FOR EACH ROW
EXECUTE FUNCTION fn_update_updated_at();
