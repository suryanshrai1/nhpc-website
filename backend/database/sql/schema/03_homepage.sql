SET TIME ZONE 'UTC';

-- ============================================================
-- Table: homepage_sections
-- ============================================================

CREATE TABLE homepage_sections (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    section_key VARCHAR(50) NOT NULL,

    title VARCHAR(255),

    subtitle TEXT,

    display_order INTEGER NOT NULL DEFAULT 1,

    is_visible BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_homepage_sections PRIMARY KEY (id),

    CONSTRAINT uq_homepage_sections_key UNIQUE (section_key),

    CONSTRAINT chk_homepage_sections_display_order
        CHECK (display_order > 0)

);

CREATE INDEX idx_homepage_sections_order
ON homepage_sections(display_order);

CREATE INDEX idx_homepage_sections_visible
ON homepage_sections(is_visible);

CREATE TRIGGER trg_homepage_sections_updated_at
BEFORE UPDATE ON homepage_sections
FOR EACH ROW
EXECUTE FUNCTION fn_update_updated_at();


-- ============================================================
-- Table: homepage_content
-- ============================================================

CREATE TABLE homepage_content (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    section_id BIGINT NOT NULL,

    content_key VARCHAR(100) NOT NULL,

    content_value TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_homepage_content PRIMARY KEY (id),

    CONSTRAINT fk_homepage_content_section
        FOREIGN KEY (section_id)
        REFERENCES homepage_sections(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_homepage_content_key
        UNIQUE(section_id, content_key)

);

CREATE INDEX idx_homepage_content_section
ON homepage_content(section_id);

CREATE TRIGGER trg_homepage_content_updated_at
BEFORE UPDATE ON homepage_content
FOR EACH ROW
EXECUTE FUNCTION fn_update_updated_at();


